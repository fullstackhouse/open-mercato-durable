#!/usr/bin/env node
// Emits the package-level `generated/` entity descriptor the Open Mercato CLI reads.
//
// Why this is needed at all: the CLI derives entity ids and field names by parsing exported
// `@Entity()` class declarations out of the module's `data/entities` file. For a package it
// parses the BUILT file, and esbuild lowers a decorated class into `var X = class {}` plus a
// `__decorateClass` call — so there is no exported class declaration left to find, and the
// module contributes no entity ids at all. The runtime is unaffected (the app spreads our
// namespace into MikroORM, which gets the real class); only the static metadata disappears.
//
// Generated from `core/schema.ts`, which is the definition of the table, so the descriptor
// cannot drift from the DDL the migration applies.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { CREATE_TABLE } = await import(path.join(pkgDir, 'dist/core/schema.js'))

const MODULE_ID = 'durable_work'
// The CLI keys entities by the snake_case of the CLASS name, not the table name.
const ENTITY = 'durable_work_job'

const body = CREATE_TABLE.slice(CREATE_TABLE.indexOf('(') + 1, CREATE_TABLE.lastIndexOf(')'))
const columns = body
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => line.split(/\s+/)[0])
  .filter((name) => /^[a-z_]+$/.test(name))

if (columns.length < 30) {
  console.error(`gen-entity-ids: parsed only ${columns.length} columns from CREATE_TABLE; refusing to write a truncated descriptor`)
  process.exit(1)
}

const out = path.join(pkgDir, 'generated')
rmSync(out, { recursive: true, force: true })
mkdirSync(path.join(out, 'entities', ENTITY), { recursive: true })

writeFileSync(
  path.join(out, 'entities.ids.generated.ts'),
  `// GENERATED by scripts/gen-entity-ids.mjs from core/schema.ts. Do not edit.\n` +
    `export const M = ${JSON.stringify({ [MODULE_ID]: MODULE_ID }, null, 2)} as const\n` +
    `export const E = ${JSON.stringify({ [MODULE_ID]: { [ENTITY]: `${MODULE_ID}:${ENTITY}` } }, null, 2)} as const\n`,
)
writeFileSync(
  path.join(out, 'entities', ENTITY, 'index.ts'),
  columns.map((c) => `export const ${c} = ${JSON.stringify(c)};`).join('\n') + '\n',
)

console.log(`gen-entity-ids: ${MODULE_ID}.${ENTITY} → ${columns.length} fields`)
